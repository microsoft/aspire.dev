/** Loads a page-specific module when an element matching `selector` is on the page. */
function when(selector: string, load: () => Promise<unknown>): void {
  if (document.querySelector(selector)) {
    load().catch((error: unknown) => console.error(`[site] failed to load the script for ${selector}`, error));
  }
}

